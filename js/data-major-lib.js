/* ---------- 主入口：书目 → {points, choice, judge, short} ---------- */
function majorContentFor(name) {
  const area = majorAreaFor(name);
  if (!area) return Object.assign({ missing: true }, majorGenericFor(name));
  const clone = (arr) => (arr || []).map((x) => Object.assign({}, x));
  return {
    missing: false,
    alias: area.alias,
    points: clone(area.points),
    choice: clone(area.choice),
    judge: clone(area.judge),
    short: clone(area.short)
  };
}

