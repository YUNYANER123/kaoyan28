/* ---------- 工具：书名缩写 ---------- */
function shortBookName(raw) {
  let n = String(raw || '').replace(/[《》\s]/g, '');
  if (!n) return '';
  for (let i = 0; i < BOOK_ABBR_RULES.length; i++) {
    if (BOOK_ABBR_RULES[i][0].test(n)) return BOOK_ABBR_RULES[i][1];
  }
  let m = n
    .replace(/[（(]?第[一二三四五六七八九十\d]+版[）)]?/g, '')
    .replace(/(基础|教程|原理|概论|导论|简明|新编|实用|考研|复习|指导|讲义|教材|课本)/g, '');
  if (!m) m = n;
  return m.length > 4 ? m.slice(0, 4) : m;
}

/* ---------- 工具：书目 → 科目领域 ---------- */
function majorAreaFor(name) {
  const n = String(name || '');
  if (!n) return null;
  for (let i = 0; i < MAJOR_LIB.length; i++) {
    const area = MAJOR_LIB[i];
    for (let j = 0; j < area.match.length; j++) {
      if (area.match[j].test(n)) return area;
    }
  }
  return null;
}

